"""Renders reports/report.md from ``ReportData``."""

from __future__ import annotations

from datetime import timedelta

from saasreport.data import CHANNEL_LABELS, ReportData, pooled_retention
from saasreport.formatting import month_label, optional, pct, signed_usd, usd

RETENTION_CHECKPOINTS = (1, 3, 6, 12, 24)


def table(headers: list[str], rows: list[list[str]], numeric_columns: int = 1) -> list[str]:
    """A markdown table; every column from ``numeric_columns`` on is right-aligned."""
    alignment = ["---" if index < numeric_columns else "---:" for index in range(len(headers))]
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join(alignment) + " |"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return lines


def render_markdown(data: ReportData) -> str:
    last = data.last_month
    window = data.trailing_months(12)
    start_mrr = window[0].starting_mrr
    period = f"{month_label(window[0].month_start)} to {month_label(last.month_start)}"
    gains = sum(month.new + month.expansion + month.reactivation for month in window)
    losses = sum(month.contraction + month.churned for month in window)
    churned = sum(month.churned for month in window)
    involuntary = sum(month.involuntary_churned for month in window)
    logo_churn = sum(month.churned_customers for month in window) / max(
        1, sum(month.starting_customers for month in window)
    )

    lines = [
        "# Tallyloom metrics report",
        "",
        "> **All data is synthetic.** Tallyloom is a fictional SaaS company; every number below",
        "> comes from data generated by `saasgen` and transformed by the dbt marts in this",
        "> repository. Regenerate this file with `make report`.",
        "",
        f"Data covers {month_label(data.bridge[0].month_start)} to "
        f"{month_label(last.month_start)}. MRR is measured on the last day of each month.",
        "",
        f"## Headline ({month_label(last.month_start)})",
        "",
    ]
    headline = [
        ["Ending MRR", usd(last.ending_mrr)],
        ["ARR (MRR x 12)", usd(last.ending_mrr * 12)],
        ["Paying customers", f"{last.ending_customers:,}"],
        ["ARPA (MRR per paying customer)", usd(last.ending_mrr / max(1, last.ending_customers))],
        [f"MRR growth, {period}", optional(_growth(start_mrr, last.ending_mrr), "{:+.1%}")],
        [f"Net new MRR, {period}", signed_usd(last.ending_mrr - start_mrr)],
        [f"Quick ratio, {period}", optional(gains / -losses if losses else None, "{:.2f}")],
        [f"Average monthly logo churn, {period}", pct(logo_churn, 2)],
    ]
    lines += table(["Metric", "Value"], headline)

    lines += [
        "",
        "![Ending MRR by month](figures/mrr_trend.png)",
        "",
        f"## MRR bridge, {period}",
        "",
        "![MRR bridge](figures/mrr_bridge.png)",
        "",
    ]
    before = month_label(window[0].month_start - timedelta(days=1))
    bridge_rows = [
        [f"Starting MRR (end of {before})", usd(start_mrr)],
        ["New", signed_usd(sum(month.new for month in window))],
        ["Expansion", signed_usd(sum(month.expansion for month in window))],
        ["Reactivation", signed_usd(sum(month.reactivation for month in window))],
        ["Contraction", signed_usd(sum(month.contraction for month in window))],
        ["Churn", signed_usd(churned)],
        [f"Ending MRR (end of {month_label(last.month_start)})", usd(last.ending_mrr)],
    ]
    lines += table(["Movement", "MRR"], bridge_rows)
    if churned:
        lines += [
            "",
            f"Failed payments (involuntary churn) caused {pct(involuntary / churned, 0)} of the "
            "churned MRR in this period.",
        ]

    lines += [
        "",
        "## Cohort retention",
        "",
        "![Cohort retention](figures/cohort_retention.png)",
        "",
    ]
    points = {point.months_since_start: point for point in pooled_retention(data.cohorts)}
    retention_rows = [
        [
            str(months),
            str(points[months].cohorts),
            pct(points[months].logo_retention),
            pct(points[months].net_revenue_retention),
        ]
        for months in RETENTION_CHECKPOINTS
        if months in points
    ]
    lines += table(
        ["Months since start", "Cohorts", "Logo retention", "Net revenue retention"],
        retention_rows,
    )
    lines += [
        "",
        "Rates are pooled over every cohort old enough to reach that month (ratio of sums).",
        "",
        "## Unit economics, trailing 12 months",
        "",
        "![CAC payback by channel](figures/cac_payback.png)",
        "",
    ]
    economics_rows = [
        [
            CHANNEL_LABELS.get(row.channel, row.channel),
            usd(row.marketing_spend),
            f"{row.new_customers:,}",
            optional(row.cac, "${:,.0f}"),
            optional(row.arpa, "${:,.0f}"),
            optional(row.monthly_churn, "{:.2%}"),
            optional(row.ltv, "${:,.0f}"),
            optional(row.payback_months, "{:.1f}"),
            optional(row.ltv_to_cac, "{:.1f}x"),
        ]
        for row in data.economics
    ]
    lines += table(
        [
            "Channel",
            "Spend",
            "New customers",
            "CAC",
            "ARPA",
            "Monthly logo churn",
            "LTV",
            "Payback (months)",
            "LTV:CAC",
        ],
        economics_rows,
    )
    margin = data.economics[0].gross_margin if data.economics else 0.0
    lines += [
        "",
        f"LTV = ARPA x {margin:.0%} gross margin / monthly logo churn (constant churn, "
        "undiscounted). Organic customers have no attributed spend, so CAC is n/a.",
        "",
        "## Funnel conversion",
        "",
        "![Funnel conversion](figures/funnel.png)",
        "",
    ]
    funnel_rows = [
        [
            CHANNEL_LABELS.get(row.channel, row.channel),
            f"{row.signups:,}",
            f"{row.trials:,}",
            f"{row.paid:,}",
            pct(row.signup_to_trial),
            pct(row.trial_to_paid),
            pct(row.signup_to_paid),
        ]
        for row in data.funnel
    ]
    lines += table(
        [
            "Channel",
            "Signups",
            "Trials",
            "Paid",
            "Signup to trial",
            "Trial to paid",
            "Signup to paid",
        ],
        funnel_rows,
    )
    lines += [
        "",
        "Only signup cohorts that ended at least 30 days before the data ends are included.",
    ]

    if data.plan_mix:
        total_mrr = sum(plan.mrr for plan in data.plan_mix)
        lines += ["", f"## MRR by plan ({month_label(last.month_start)})", ""]
        plan_rows = [
            [
                plan.plan_name,
                f"{plan.customers:,}",
                usd(plan.mrr),
                pct(plan.mrr / total_mrr) if total_mrr else "n/a",
                pct(plan.grandfathered_mrr / plan.mrr) if plan.mrr else "n/a",
            ]
            for plan in data.plan_mix
        ]
        lines += table(
            ["Plan", "Customers", "MRR", "Share of MRR", "Still on pre-change price"], plan_rows
        )
        lines += [
            "",
            "Existing subscriptions keep their price after the list-price change until they "
            "change plan (grandfathering).",
        ]
    return "\n".join(lines) + "\n"


def _growth(start: float, end: float) -> float | None:
    return (end - start) / start if start else None
